export function formatShariaItem(item) {
  let text = `📖 <b>${item.field} 🌟</b>\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `📌 <b>العنوان:</b> <b>${item.title}</b>\n\n`;
  text += `${item.content}\n\n`;
  text += `🇪🇬 <b>الزتونة بالمصري السهل:</b>\n${item.egyptian_takeaway}\n\n`;
  text += `💡 <b>الخلاصة والتطبيق:</b>\n<b>"${item.action_takeaway}"</b> 🎯\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `✨ <i>«مَن يُرِدِ اللهُ بهِ خيراً يُفقِّههُ في الدِّين» (متفق عليه).</i>`;
  return text;
}

export function getRandomShariaCapsule(excludeId = null) {
  const filtered = excludeId ? SHARIA_CAPSULES.filter(c => c.id !== excludeId) : SHARIA_CAPSULES;
  const item = filtered[Math.floor(Math.random() * filtered.length)] || SHARIA_CAPSULES[0];
  return { ...item, formattedText: formatShariaItem(item) };
}

export function getShariaCapsuleById(id) {
  return SHARIA_CAPSULES.find(c => c.id === id) || SHARIA_CAPSULES[0];
}
