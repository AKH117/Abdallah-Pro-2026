export function formatStatesmanMistake(item) {
  let text = `🏛️ <b>فقرة أخطاء الذين مضوا — درس استراتيجي للحاكم والخليفة 📜</b>\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `📌 <b>العنوان:</b> <b>${item.title}</b>\n`;
  text += `👤 <b>الحاكم / الدولة:</b> ${item.ruler}\n\n`;
  text += `⚠️ <b>الخطأ الكارثي اللي عمله:</b>\n${item.fatal_error}\n\n`;
  text += `💥 <b>النتيجة:</b>\n${item.consequence}\n\n`;
  text += `🇪🇬 <b>الزتونة والدرس بالمصري الصميم:</b>\n${item.egyptian_takeaway}\n\n`;
  text += `👑 <b>توجيه رجل الدولة لـ د. عبدالله:</b>\n<b>"${item.statesman_correction}"</b> 🎯\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `💡 <i>"اللي بيتعلم من أخطاء التاريخ.. بيحكم المستقبل!"</i>`;
  return text;
}

export function formatStatesmanPearl(item) {
  let text = `👑 <b>كبسولة صناعة رجل الدولة والخليفة 🏛️</b>\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `🎯 <b>المحور:</b> <b>${item.title}</b>\n\n`;
  text += `💡 <b>الدرس القيادي:</b>\n${item.pearl}\n\n`;
  text += `🇪🇬 <b>الزتونة بالمصري:</b>\n${item.egyptian_takeaway}\n\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `🩺 <i>"العلم الطبي بيشفي الأبدان.. والحكمة والقيادة بتبني الأمم!"</i> 🔥`;
  return text;
}

export function getRandomPastRulerMistake(excludeId = null) {
  const filtered = excludeId ? PAST_RULERS_MISTAKES.filter(m => m.id !== excludeId) : PAST_RULERS_MISTAKES;
  const item = filtered[Math.floor(Math.random() * filtered.length)] || PAST_RULERS_MISTAKES[0];
  return { ...item, formattedText: formatStatesmanMistake(item) };
}

export function getRandomStatesmanPearl() {
  const item = STATESMAN_PILLARS[Math.floor(Math.random() * STATESMAN_PILLARS.length)];
  return { ...item, formattedText: formatStatesmanPearl(item) };
}
